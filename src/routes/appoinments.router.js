import { Router } from "express";
import {
  appointmentDetail,
  approveAppointment,
  cancelAppointment,
  createAppointment,
  getAllAppointmentsAdmin,
  getAppointmentByStatus,
  getDoctorAppointments,
  getPatientAppointments,
  rejectAppointment,
  updateAppointmentStatus,
  deleteAppointment,
} from "../controllers/appoinments.controller.js";
import { authoriseRoles, isAuthenticatedUser } from "../utils/auth.js";

const appointmentRouter = Router();
appointmentRouter.post(
  "/new-appoinment",
  isAuthenticatedUser,
  authoriseRoles("Patient"),
  createAppointment,
);
appointmentRouter.get(
  "/all-appointments",
  isAuthenticatedUser,
  authoriseRoles("Patient"),
  getPatientAppointments,
);
appointmentRouter.get(
  "/doctor-appointments",
  isAuthenticatedUser,
  authoriseRoles("Doctor"),
  getDoctorAppointments,
);
appointmentRouter.put(
  "/approve/:id",
  isAuthenticatedUser,
  authoriseRoles("Doctor"),
  approveAppointment,
);
appointmentRouter.put(
  "/rejected/:id",
  isAuthenticatedUser,
  authoriseRoles("Doctor"),
  rejectAppointment,
);
appointmentRouter.put(
  "/cancel/:id",
  isAuthenticatedUser,
  authoriseRoles("Doctor"),
  cancelAppointment,
);
appointmentRouter.get(
  "/all",
  isAuthenticatedUser,
  authoriseRoles("Admin"),
  getAllAppointmentsAdmin,
);
appointmentRouter.get(
  "/appointment-detail/:id",
  isAuthenticatedUser,
  authoriseRoles("Admin"),
  appointmentDetail,
);
appointmentRouter.get(
  "/status/:status",
  isAuthenticatedUser,
  authoriseRoles("Admin"),
  getAppointmentByStatus,
);
appointmentRouter.put(
  "/update-status/:id",
  isAuthenticatedUser,
  authoriseRoles("Admin"),
  updateAppointmentStatus,
);
appointmentRouter.delete(
  "/delete/:id",
  isAuthenticatedUser,
  authoriseRoles("Admin"),
  deleteAppointment,
);
export default appointmentRouter;
